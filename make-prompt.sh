#!/bin/sh
# Builds PROMPT.md (paste into any Claude chat) from the skill, so they never drift.
set -eu
cd "$(dirname "$0")"
skill=.claude/skills/html-intro
{
  echo "<!-- Generated by make-prompt.sh from $skill. Edit those files, not this one. -->"
  echo "<!-- Copy everything below this line into a new Claude chat. -->"
  echo
  sed '1,/^---$/{/^---$/!d;};1,/^---$/d' "$skill/SKILL.md" | sed '1{/^$/d;}'
  echo
  echo "## Appendix: pages.yml"
  echo
  echo '```yaml'
  cat "$skill/pages.yml"
  echo '```'
  echo
  echo "---"
  echo
  echo "Start now: greet me in one or two sentences and begin with Step 0."
} > PROMPT.md
